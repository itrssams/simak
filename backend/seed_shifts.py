def seed_shifts():
    print(f"=== SEEDING MASTER SHIFT ({len(SHIFTS_DATA)} SHIFT DEFINITIONS) ===")
    # Normalisasi kode lama 'St' -> 'ST' bila ada
    for old_st in Shift.objects.filter(kode='St'):
        if not Shift.objects.filter(kelompok=old_st.kelompok, kode='ST').exclude(id=old_st.id).exists():
            old_st.kode = 'ST'
            old_st.save(update_fields=['kode'])

    created_count = 0
    updated_count = 0

    for item in SHIFTS_DATA:
        obj, created = Shift.objects.update_or_create(
            kelompok=item['kelompok'],
            kode=item['kode'],
            defaults=item
        )
        if created:
            created_count += 1
        else:
            updated_count += 1

    print(f"Hasil: {created_count} Shift baru dibuat, {updated_count} Shift diupdate.")
    print(f"Total Shift di Database: {Shift.objects.count()}")


if __name__ == '__main__':
    seed_shifts()
